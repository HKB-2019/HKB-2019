-- MASQ. shop schema (Postgres)
--
-- Money is stored in KOBO as integers, never naira as floats. 0.1 + 0.2 is not
-- 0.3 in binary floating point, and a shop that rounds a fraction of a kobo per
-- line eventually disagrees with its payment provider about what it charged.
-- Paystack's API also takes and returns kobo, so this keeps one unit end to end.
--
-- Every statement is IF NOT EXISTS, so this file runs on every boot and only
-- ever adds what is missing.

-- Product photos uploaded through the admin. Stored in the database, not on
-- disk, because a free host wipes its disk at every restart. Each photo is
-- kept twice — `data` for ordinary screens, `data_2x` at double width for
-- sharp ones — already resized and compressed by the admin's browser.
CREATE TABLE IF NOT EXISTS images (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mime        TEXT        NOT NULL CHECK (mime IN ('image/webp','image/jpeg','image/png')),
  data        BYTEA       NOT NULL,
  data_2x     BYTEA       NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS products (
  id          TEXT        PRIMARY KEY,
  name        TEXT        NOT NULL,
  price_kobo  INTEGER     NOT NULL CHECK (price_kobo > 0),
  -- A built-in photo shipped with the site (assets/img/…). An uploaded photo,
  -- when there is one, takes over through image_id.
  img         TEXT        NOT NULL DEFAULT '',
  image_id    INTEGER     REFERENCES images(id) ON DELETE SET NULL,
  badge       TEXT,
  -- Where it appears. The drop grid shows `featured` pieces first and the rest
  -- behind VIEW ALL; the Essentials carousel is a separate selection.
  in_drop       BOOLEAN   NOT NULL DEFAULT TRUE,
  featured      BOOLEAN   NOT NULL DEFAULT TRUE,
  in_essentials BOOLEAN   NOT NULL DEFAULT FALSE,
  -- Off sale: not shown and cannot be bought. Products are hidden rather than
  -- deleted, so past orders and their photos keep making sense.
  hidden      BOOLEAN     NOT NULL DEFAULT FALSE,
  -- Postgres has no insertion order to fall back on, so display order is kept
  -- explicitly rather than hoped for.
  position    INTEGER     NOT NULL DEFAULT 0,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Databases created before these columns existed get them here. A no-op on a
-- fresh database.
ALTER TABLE products ADD COLUMN IF NOT EXISTS image_id      INTEGER REFERENCES images(id) ON DELETE SET NULL;
ALTER TABLE products ADD COLUMN IF NOT EXISTS in_drop       BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE products ADD COLUMN IF NOT EXISTS featured      BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE products ADD COLUMN IF NOT EXISTS in_essentials BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE products ADD COLUMN IF NOT EXISTS hidden        BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE products ALTER COLUMN img SET DEFAULT '';
-- The product page: what it is, and how to look after it. Plain text.
ALTER TABLE products ADD COLUMN IF NOT EXISTS description TEXT NOT NULL DEFAULT '';
ALTER TABLE products ADD COLUMN IF NOT EXISTS details     TEXT NOT NULL DEFAULT '';
-- A drop: on sale from this moment, invisible and unbuyable before it.
ALTER TABLE products ADD COLUMN IF NOT EXISTS available_at TIMESTAMPTZ;

-- The first version marked the pieces behind VIEW ALL with `is_extra`. Carry
-- that over once, then drop the column, so this never runs again and never
-- overwrites placement the owner has since changed in the admin.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
              WHERE table_name = 'products' AND column_name = 'is_extra') THEN
    UPDATE products SET featured = NOT is_extra, in_essentials = is_extra;
    ALTER TABLE products DROP COLUMN is_extra;
  END IF;
END $$;

-- Photos beyond the main one, shown in the product page's gallery. The main
-- photo stays on products (image_id, or the built-in img), so a product with
-- no extra photos needs nothing here.
CREATE TABLE IF NOT EXISTS product_photos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id  TEXT    NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  image_id    INTEGER NOT NULL REFERENCES images(id) ON DELETE CASCADE,
  position    INTEGER NOT NULL DEFAULT 0,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_product_photos ON product_photos(product_id, position);

-- One row per sellable thing. A size is not a property of a product, it is a
-- separate thing with its own stock count — "THE FACE TEE" is never in stock,
-- "THE FACE TEE, size M" is.
CREATE TABLE IF NOT EXISTS variants (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id  TEXT    NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  size        TEXT    NOT NULL,
  stock       INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  UNIQUE (product_id, size)
);

-- Colours. A product the owner gives colours to is sold as colour + size:
-- "THE FACE TEE, Black, M" has its own stock count, apart from White, M. A
-- product with no colours keeps one row per size with colour ''. A colour may
-- have its own photo, shown first on the product page when it is picked.
CREATE TABLE IF NOT EXISTS product_colours (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id  TEXT    NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  name        TEXT    NOT NULL,
  hex         TEXT    NOT NULL CHECK (hex ~ '^#[0-9a-f]{6}$'),
  image_id    INTEGER REFERENCES images(id) ON DELETE SET NULL,
  position    INTEGER NOT NULL DEFAULT 0,
  UNIQUE (product_id, name)
);

-- A colour's photo that shipped with the site (assets/img/…); an upload
-- (image_id) takes over from it, as for a product's main photo.
ALTER TABLE product_colours ADD COLUMN IF NOT EXISTS img TEXT NOT NULL DEFAULT '';
ALTER TABLE variants ADD COLUMN IF NOT EXISTS colour TEXT NOT NULL DEFAULT '';
-- One stock count per product, colour and size (it was per product and size).
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'variants_product_id_size_key') THEN
    ALTER TABLE variants DROP CONSTRAINT variants_product_id_size_key;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'variants_product_colour_size_key') THEN
    ALTER TABLE variants ADD CONSTRAINT variants_product_colour_size_key UNIQUE (product_id, colour, size);
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS customers (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email      TEXT        NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- The owner's own words about a person (the CUSTOMERS tab): tags such as
-- VIP or wholesale, and private notes. Everything else about a customer is
-- read from their orders, the mailing list and their restock requests.
ALTER TABLE customers ADD COLUMN IF NOT EXISTS tags       JSONB       NOT NULL DEFAULT '[]'::jsonb;
ALTER TABLE customers ADD COLUMN IF NOT EXISTS notes      TEXT        NOT NULL DEFAULT '';
ALTER TABLE customers ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ;

-- status:
--   pending    stock is held; the customer is on (or left) Paystack's page
--   paid       Paystack confirmed the full amount
--   failed     Paystack said the charge failed; stock returned
--   abandoned  never paid; stock returned by the sweeper
--   refund_due paid AFTER the order was given up on, and the stock had
--              already gone to someone else. The customer has been charged for
--              something that cannot be sent, so a person must refund them.
--   refunded   the owner refunded it in Paystack and marked it so here
--
-- Stock is held at `pending` so two people cannot both buy the last jacket
-- while one of them is still on Paystack's page.
CREATE TABLE IF NOT EXISTS orders (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference      TEXT        NOT NULL UNIQUE,
  customer_id    INTEGER     REFERENCES customers(id),
  email          TEXT        NOT NULL,
  status         TEXT        NOT NULL DEFAULT 'pending'
                             CHECK (status IN ('pending','paid','failed','abandoned','refund_due','refunded')),
  subtotal_kobo  INTEGER     NOT NULL CHECK (subtotal_kobo > 0),
  -- Delivery, priced by the server from the owner's settings. Paystack is
  -- asked for subtotal + shipping, and that sum is what a payment must match.
  shipping_kobo  INTEGER     NOT NULL DEFAULT 0 CHECK (shipping_kobo >= 0),
  currency       TEXT        NOT NULL DEFAULT 'NGN',
  -- Who and where. Without these an order is paid for and undeliverable.
  customer_name  TEXT,
  phone          TEXT,
  address        JSONB,
  delivery_zone  TEXT,
  paystack_id    TEXT,
  paid_at        TIMESTAMPTZ,
  fulfilled_at   TIMESTAMPTZ,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE orders ADD COLUMN IF NOT EXISTS shipping_kobo INTEGER NOT NULL DEFAULT 0;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS customer_name TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS phone         TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS address       JSONB;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS delivery_zone TEXT;
-- A discount code, if one was used: the code as typed, and what it took off
-- the items. Paystack is asked for subtotal − discount + shipping.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS discount_code TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS discount_kobo INTEGER NOT NULL DEFAULT 0 CHECK (discount_kobo >= 0);
-- How it was sent, shown to the customer on their order page.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS courier       TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS tracking      TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS refunded_at   TIMESTAMPTZ;

-- Where the visit that placed the order came from (see server/lib/analytics.js),
-- kept on the order so sales by source outlive the 90 days of visit detail.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS session_id    TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS channel       TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS campaign      TEXT;

-- `refunded` came later: the owner returned the money from Paystack's
-- dashboard and marked it here. Older databases have the status check
-- without it, so it is replaced once.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'orders_status_check'
                    AND pg_get_constraintdef(oid) LIKE '%refunded''%') THEN
    ALTER TABLE orders DROP CONSTRAINT IF EXISTS orders_status_check;
    ALTER TABLE orders ADD CONSTRAINT orders_status_check
      CHECK (status IN ('pending','paid','failed','abandoned','refund_due','refunded'));
  END IF;
END $$;

-- Line items keep their own copy of name and price. A product's price may
-- change next week; what this customer was charged must not.
CREATE TABLE IF NOT EXISTS order_items (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id        INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id      TEXT    NOT NULL,
  variant_id      INTEGER NOT NULL,
  name            TEXT    NOT NULL,
  size            TEXT    NOT NULL,
  unit_price_kobo INTEGER NOT NULL CHECK (unit_price_kobo > 0),
  qty             INTEGER NOT NULL CHECK (qty > 0)
);
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS colour TEXT NOT NULL DEFAULT '';

-- Every webhook Paystack sends, recorded before it is acted on. Paystack
-- retries, so the same event arrives more than once; the UNIQUE event_id is
-- what makes handling it idempotent.
CREATE TABLE IF NOT EXISTS webhook_events (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id     TEXT        NOT NULL UNIQUE,
  event_type   TEXT        NOT NULL,
  reference    TEXT,
  payload      TEXT        NOT NULL,
  processed_at TIMESTAMPTZ,
  received_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Small pieces of shop state that must survive a restart and cannot live in
-- the host's environment variables: the admin password hash (when chosen in
-- the browser), delivery fees, the footer pages, social links, the film link.
-- Values are JSON text, validated in server/lib/settings.js before storing.
CREATE TABLE IF NOT EXISTS settings (
  key        TEXT        PRIMARY KEY,
  value      TEXT        NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- The mailing list. Only the address and when it arrived; nothing is sent from
-- here — the owner exports it to whatever email tool they use.
CREATE TABLE IF NOT EXISTS subscribers (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email      TEXT        NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Discount codes. `uses` counts orders holding the code — taken at checkout
-- like stock, so a limit of 50 cannot be passed by 60 people paying at
-- once, and given back if the payment never comes.
CREATE TABLE IF NOT EXISTS discount_codes (
  code           TEXT        PRIMARY KEY,          -- stored in capitals
  kind           TEXT        NOT NULL CHECK (kind IN ('percent','fixed')),
  amount         INTEGER     NOT NULL CHECK (amount > 0),   -- percent, or kobo
  min_spend_kobo INTEGER     NOT NULL DEFAULT 0 CHECK (min_spend_kobo >= 0),
  max_uses       INTEGER     CHECK (max_uses IS NULL OR max_uses > 0),
  uses           INTEGER     NOT NULL DEFAULT 0 CHECK (uses >= 0),
  ends_at        TIMESTAMPTZ,
  active         BOOLEAN     NOT NULL DEFAULT TRUE,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- "Tell me when it's back": one row per person per sold-out size. Nothing is
-- sent from here; the owner sees the list in the admin.
CREATE TABLE IF NOT EXISTS stock_alerts (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id TEXT        NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  size       TEXT        NOT NULL,
  email      TEXT        NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (product_id, size, email)
);
ALTER TABLE stock_alerts ADD COLUMN IF NOT EXISTS colour TEXT NOT NULL DEFAULT '';
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'stock_alerts_product_id_size_email_key') THEN
    ALTER TABLE stock_alerts DROP CONSTRAINT stock_alerts_product_id_size_email_key;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'stock_alerts_product_colour_size_email_key') THEN
    ALTER TABLE stock_alerts ADD CONSTRAINT stock_alerts_product_colour_size_email_key
      UNIQUE (product_id, colour, size, email);
  END IF;
END $$;

-- Every count the owner changes in the admin, newest last: what was left to
-- sell before and after, and the shelf count it came from (null when the
-- number was set directly). Checkout's own changes are not here: the orders
-- are their record. Kept by name, so it still reads after a product goes.
CREATE TABLE IF NOT EXISTS stock_log (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  variant_id   INTEGER     REFERENCES variants(id) ON DELETE SET NULL,
  product_id   TEXT        NOT NULL,
  name         TEXT        NOT NULL,
  colour       TEXT        NOT NULL DEFAULT '',
  size         TEXT        NOT NULL,
  stock_before INTEGER     NOT NULL,
  stock_after  INTEGER     NOT NULL,
  shelf        INTEGER,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS stock_log_recent ON stock_log (created_at DESC, id DESC);
-- What kind of change: 'count' (a shelf count), 'set' (left to sell typed
-- directly) or 'delivery' (pieces received, added on top), with the owner's
-- note for a delivery — the supplier, an invoice number.
ALTER TABLE stock_log ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'count';
ALTER TABLE stock_log ADD COLUMN IF NOT EXISTS note TEXT NOT NULL DEFAULT '';

-- Visits, counted without cookies or personal data (server/lib/analytics.js).
-- One row per thing that happened: a page seen, a piece viewed, a bag add.
-- Kept 90 days, then folded into analytics_daily.
CREATE TABLE IF NOT EXISTS events (
  id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  name         TEXT        NOT NULL,
  session      TEXT        NOT NULL,   -- random per browser tab visit
  visitor      TEXT        NOT NULL,   -- scrambled with a secret replaced daily
  path         TEXT,
  channel      TEXT,
  referrer     TEXT,                   -- the referring site's name only
  utm_source   TEXT,
  utm_medium   TEXT,
  utm_campaign TEXT,
  device       TEXT,
  os           TEXT,
  browser      TEXT,
  country      TEXT,
  returning_visitor BOOLEAN,
  product_id   TEXT,
  size         TEXT,
  value_kobo   INTEGER,
  engaged_ms   INTEGER
);
CREATE INDEX IF NOT EXISTS idx_events_at      ON events(at);
CREATE INDEX IF NOT EXISTS idx_events_session ON events(session, at);

CREATE TABLE IF NOT EXISTS analytics_daily (
  day        DATE   PRIMARY KEY,           -- Lagos date
  visitors   INTEGER NOT NULL,
  visits     INTEGER NOT NULL,
  pageviews  INTEGER NOT NULL,
  bounces    INTEGER NOT NULL,
  engaged_ms BIGINT  NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_orders_status_created ON orders(status, created_at);
CREATE INDEX IF NOT EXISTS idx_items_order           ON order_items(order_id);
CREATE INDEX IF NOT EXISTS idx_variants_product      ON variants(product_id);

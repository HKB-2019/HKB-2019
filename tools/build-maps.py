"""Turns Natural Earth outlines into the SVG paths the VISITORS tab draws.

Natural Earth is public domain (naturalearthdata.com). Download:
  https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson
  https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_1_states_provinces.geojson

  python3 tools/build-maps.py <countries.geojson> <states_provinces.geojson>

Writes src/data/maps.js. Standard library only.
"""
import json, math, sys

def simplify(pts, tol):
    """Douglas-Peucker, iterative."""
    if len(pts) < 4:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]; bx, by = pts[b]
        dx, dy = bx - ax, by - ay
        norm = math.hypot(dx, dy)
        far, at = -1, None
        for i in range(a + 1, b):
            px, py = pts[i]
            # A closed outline starts and ends on the same point: measure
            # from that point instead of from a line of no length.
            d = (abs(dy * px - dx * py + bx * ay - by * ax) / norm) if norm > 1e-9 else math.hypot(px - ax, py - ay)
            if d > far:
                far, at = d, i
        if far > tol and at is not None:
            keep[at] = True
            stack += [(a, at), (at, b)]
    return [p for p, k in zip(pts, keep) if k]

def rings(geom):
    if geom['type'] == 'Polygon':
        return [geom['coordinates'][0]]          # outer rings only: no lakes at this size
    if geom['type'] == 'MultiPolygon':
        return [poly[0] for poly in geom['coordinates']]
    return []

def path(feature_rings, project, tol, min_area):
    out = []
    for ring in feature_rings:
        pts = [project(lon, lat) for lon, lat in ring]
        xs = [p[0] for p in pts]; ys = [p[1] for p in pts]
        if (max(xs) - min(xs)) * (max(ys) - min(ys)) < min_area:
            continue                               # specks vanish at this size
        pts = simplify(pts, tol)
        if len(pts) < 3:
            continue
        out.append('M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in pts) + 'Z')
    return ''.join(out)

# Equal Earth (Šavrič, Patterson & Jenny 2018): areas true, shapes familiar.
A1, A2, A3, A4 = 1.340264, -0.081106, 0.000893, 0.003796
M = math.sqrt(3) / 2
def equal_earth(lon, lat):
    l, p = math.radians(lon), math.radians(lat)
    t = math.asin(M * math.sin(p)); t2 = t * t; t6 = t2 * t2 * t2
    x = l * math.cos(t) / (M * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2)))
    y = t * (A1 + A2 * t2 + t6 * (A3 + A4 * t2))
    return x, -y

def fit(features, project, width):
    xs, ys = [], []
    for f in features:
        for ring in rings(f['geometry']):
            for lon, lat in ring:
                x, y = project(lon, lat); xs.append(x); ys.append(y)
    x0, y0 = min(xs), min(ys)
    k = width / (max(xs) - x0)
    height = (max(ys) - y0) * k
    return (lambda lon, lat: ((project(lon, lat)[0] - x0) * k, (project(lon, lat)[1] - y0) * k)), round(height)

world = [f for f in json.load(open(sys.argv[1]))['features'] if f['properties']['ISO_A2_EH'] != 'AQ']
wproj, wh = fit(world, equal_earth, 1000)
countries = []
for f in world:
    code = f['properties']['ISO_A2_EH']
    d = path(rings(f['geometry']), wproj, 0.6, 1.5)
    if d:
        countries.append({'code': None if code == '-99' else code, 'name': f['properties']['NAME'], 'd': d})

RENAME = {'Federal Capital Territory': 'FCT', 'Nassarawa': 'Nasarawa'}
states_all = json.load(open(sys.argv[2]))['features']
nga = [f for f in states_all if f['properties'].get('adm0_a3') == 'NGA']
COS = math.cos(math.radians(9))                       # Nigeria's middle latitude
nproj, nh = fit(nga, lambda lon, lat: (lon * COS, -lat), 600)
states = []
for f in nga:
    name = RENAME.get(f['properties']['name'], f['properties']['name'])
    states.append({'name': name, 'd': path(rings(f['geometry']), nproj, 0.35, 0)})
states.sort(key=lambda s: s['name'])
assert len(states) == 37, len(states)

data = {
    'world': {'width': 1000, 'height': wh, 'countries': countries},
    'nigeria': {'width': 600, 'height': nh, 'states': states}
}
with open('src/data/maps.js', 'w') as out:
    out.write('/* Outlines for the VISITORS tab: countries (Equal Earth projection) and\n'
              ' * Nigeria\'s 36 states and the FCT. Generated by tools/build-maps.py from\n'
              ' * Natural Earth, which is in the public domain. */\n\n')
    out.write('export const MAPS = ' + json.dumps(data, separators=(',', ':')) + ';\n')
print(len(countries), 'countries,', len(states), 'states')
